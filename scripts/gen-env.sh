#!/usr/bin/env bash
# Creates .env or appends any missing keys with random DEV-ONLY secrets. Never overwrites an
# existing value, so it is safe to re-run after new keys are introduced. .env is gitignored.
set -euo pipefail

ENV_FILE="${1:-.env}"
umask 077
[ -f "$ENV_FILE" ] || echo "# Generated by scripts/gen-env.sh — DEV ONLY. Do not commit." > "$ENV_FILE"

ensure() { # ensure KEY VALUE
  grep -q "^$1=" "$ENV_FILE" || { echo "$1=$2" >> "$ENV_FILE"; echo "added $1"; }
}
rand() { openssl rand -hex 24; }

ensure POSTGRES_SUPERUSER_PASSWORD "$(rand)"
ensure KUBECHAOS_MIGRATOR_PASSWORD "$(rand)"
ensure KUBECHAOS_APP_PASSWORD "$(rand)"
ensure KUBECHAOS_AUDITOR_PASSWORD "$(rand)"
ensure APPROVER_MIGRATOR_PASSWORD "$(rand)"
ensure APPROVER_APP_PASSWORD "$(rand)"
ensure KEYCLOAK_ADMIN_USER "kcadmin"
ensure KEYCLOAK_ADMIN_PASSWORD "$(rand)"
# OIDC client secret shared by Keycloak (realm import placeholder) and the control plane.
ensure KUBECHAOS_OIDC_CLIENT_SECRET "$(rand)"
# Password for the seeded dev users (alice, bob, carol, dave, eve, mallory).
ensure KEYCLOAK_DEV_USER_PASSWORD "$(rand)"
